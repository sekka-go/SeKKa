CREATE OR REPLACE FUNCTION public.create_captain_line_join_request(
  actor_id integer,
  line_id integer,
  trip_on date,
  pickup_name text,
  pickup_y double precision,
  pickup_x double precision,
  dropoff_name text,
  dropoff_y double precision,
  dropoff_x double precision,
  seat_count integer DEFAULT 1,
  trip_direction text DEFAULT 'outbound'
) RETURNS public.captain_line_join_requests
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  selected_line public.captain_lines%ROWTYPE;
  request_row public.captain_line_join_requests%ROWTYPE;
  pickup_progress double precision;
  dropoff_progress double precision;
  stop_record jsonb;
  stop_index integer := 0;
  max_pickup_distance double precision := 0.5;
  max_dropoff_distance double precision := 0.5;
  configured numeric;
  pending_count integer;
  pending_limit integer := 3;
  ttl_hours integer := 12;
  route_origin_lat double precision;
  route_origin_lng double precision;
  route_destination_lat double precision;
  route_destination_lng double precision;
  route_stops jsonb;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.users u WHERE u.id = actor_id AND u.role = 'rider' AND u.verified_at IS NOT NULL AND u.deleted_at IS NULL
  ) THEN RAISE EXCEPTION 'verified rider required' USING ERRCODE = '42501'; END IF;
  PERFORM 1 FROM public.users WHERE id = actor_id FOR UPDATE;
  IF trip_direction NOT IN ('outbound','return') OR seat_count < 1 OR seat_count > 13 OR length(btrim(pickup_name)) NOT BETWEEN 2 AND 240 OR length(btrim(dropoff_name)) NOT BETWEEN 2 AND 240
     OR pickup_y NOT BETWEEN -90 AND 90 OR pickup_x NOT BETWEEN -180 AND 180 OR dropoff_y NOT BETWEEN -90 AND 90 OR dropoff_x NOT BETWEEN -180 AND 180
     OR trip_on < (now() AT TIME ZONE 'Africa/Cairo')::date THEN
    RAISE EXCEPTION 'invalid trip request' USING ERRCODE = '22023';
  END IF;

  SELECT numeric_value INTO configured FROM public.app_config WHERE config_key = 'line_stop_match_radius_km';
  IF configured IS NOT NULL THEN max_pickup_distance := configured; max_dropoff_distance := configured; END IF;
  SELECT greatest(1, numeric_value::integer) INTO pending_limit FROM public.app_config WHERE config_key = 'captain_line_join_pending_limit';
  SELECT greatest(1, numeric_value::integer) INTO ttl_hours FROM public.app_config WHERE config_key = 'captain_line_join_ttl_hours';
  SELECT count(*)::integer INTO pending_count FROM public.captain_line_join_requests
    WHERE rider_user_id = actor_id AND status = 'pending' AND expires_at > now();
  IF pending_count >= pending_limit THEN RAISE EXCEPTION 'pending join request limit reached' USING ERRCODE = '54000'; END IF;

  SELECT * INTO selected_line FROM public.captain_lines l
  WHERE l.id = line_id AND l.status = 'active'
    AND extract(dow FROM trip_on)::smallint = ANY(l.service_days)
  FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'active line not found for selected date' USING ERRCODE = 'P0002'; END IF;
  IF trip_direction = 'return' AND selected_line.return_arrival_time IS NULL THEN
    RAISE EXCEPTION 'return trip is unavailable' USING ERRCODE = '22023';
  END IF;
  IF seat_count > selected_line.seats THEN RAISE EXCEPTION 'requested seats exceed line capacity' USING ERRCODE = '22023'; END IF;

  IF trip_direction = 'return' THEN
    route_origin_lat := selected_line.destination_lat; route_origin_lng := selected_line.destination_lng;
    route_destination_lat := selected_line.origin_lat; route_destination_lng := selected_line.origin_lng;
    SELECT coalesce(jsonb_agg(value ORDER BY ordinal DESC), '[]'::jsonb) INTO route_stops
      FROM jsonb_array_elements(selected_line.intermediate_stops) WITH ORDINALITY AS stops(value, ordinal);
  ELSE
    route_origin_lat := selected_line.origin_lat; route_origin_lng := selected_line.origin_lng;
    route_destination_lat := selected_line.destination_lat; route_destination_lng := selected_line.destination_lng;
    route_stops := selected_line.intermediate_stops;
  END IF;
  pickup_progress := CASE WHEN public.sekka_geo_km(pickup_y, pickup_x, route_origin_lat, route_origin_lng) <= max_pickup_distance THEN 0 ELSE NULL END;
  dropoff_progress := CASE WHEN public.sekka_geo_km(dropoff_y, dropoff_x, route_origin_lat, route_origin_lng) <= max_dropoff_distance THEN 0 ELSE NULL END;
  FOR stop_record IN SELECT value FROM jsonb_array_elements(route_stops) LOOP
    stop_index := stop_index + 1;
    IF public.sekka_geo_km(pickup_y, pickup_x, (stop_record->>'lat')::double precision, (stop_record->>'lng')::double precision) <= max_pickup_distance THEN
      pickup_progress := coalesce(pickup_progress, stop_index::double precision);
    END IF;
    IF public.sekka_geo_km(dropoff_y, dropoff_x, (stop_record->>'lat')::double precision, (stop_record->>'lng')::double precision) <= max_dropoff_distance THEN
      dropoff_progress := coalesce(dropoff_progress, stop_index::double precision);
    END IF;
  END LOOP;
  IF public.sekka_geo_km(pickup_y, pickup_x, route_destination_lat, route_destination_lng) <= max_pickup_distance THEN
    pickup_progress := coalesce(pickup_progress, (stop_index + 1)::double precision);
  END IF;
  IF public.sekka_geo_km(dropoff_y, dropoff_x, route_destination_lat, route_destination_lng) <= max_dropoff_distance THEN
    dropoff_progress := coalesce(dropoff_progress, (stop_index + 1)::double precision);
  END IF;
  IF pickup_progress IS NULL OR dropoff_progress IS NULL OR pickup_progress >= dropoff_progress THEN
    RAISE EXCEPTION 'pickup and dropoff must follow the selected line' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.captain_line_join_requests(line_id, rider_user_id, trip_date, direction, pickup_label, pickup_lat, pickup_lng, dropoff_label, dropoff_lat, dropoff_lng, seats, expires_at)
  VALUES (selected_line.id, actor_id, trip_on, trip_direction, btrim(pickup_name), pickup_y, pickup_x, btrim(dropoff_name), dropoff_y, dropoff_x, seat_count, now() + ttl_hours * interval '1 hour')
  RETURNING * INTO request_row;
  RETURN request_row;
END;
$$;

CREATE OR REPLACE FUNCTION public.decide_captain_line_join_request(
  actor_id integer,
  request_id bigint,
  decision text,
  response_text text DEFAULT NULL
) RETURNS public.captain_line_join_requests
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  request_row public.captain_line_join_requests%ROWTYPE;
  selected_line public.captain_lines%ROWTYPE;
  committed_seats integer;
BEGIN
  IF decision NOT IN ('accepted','rejected') THEN RAISE EXCEPTION 'invalid decision' USING ERRCODE = '22023'; END IF;
  SELECT * INTO request_row FROM public.captain_line_join_requests WHERE id = request_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'join request not found' USING ERRCODE = 'P0002'; END IF;
  SELECT * INTO selected_line FROM public.captain_lines WHERE id = request_row.line_id FOR UPDATE;
  IF selected_line.captain_user_id <> actor_id THEN RAISE EXCEPTION 'line owner required' USING ERRCODE = '42501'; END IF;
  IF request_row.status <> 'pending' THEN RAISE EXCEPTION 'join request is no longer pending' USING ERRCODE = '55000'; END IF;
  IF request_row.expires_at <= now() THEN RAISE EXCEPTION 'join request expired' USING ERRCODE = '55000'; END IF;
  IF decision = 'accepted' THEN
    SELECT coalesce(sum(seats), 0)::integer INTO committed_seats
      FROM public.captain_line_join_requests
      WHERE line_id = selected_line.id AND trip_date = request_row.trip_date AND direction = request_row.direction AND status = 'accepted' AND id <> request_row.id;
    IF selected_line.status <> 'active' OR committed_seats + request_row.seats > selected_line.seats THEN
      RAISE EXCEPTION 'line has insufficient seats for this date' USING ERRCODE = '23514';
    END IF;
  END IF;
  UPDATE public.captain_line_join_requests SET status = decision, captain_response = nullif(btrim(response_text), ''), responded_at = now()
  WHERE id = request_row.id RETURNING * INTO request_row;
  RETURN request_row;
END;
$$;

CREATE OR REPLACE FUNCTION public.expire_captain_line_join_requests()
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE expired_count integer;
BEGIN
  UPDATE public.captain_line_join_requests SET status = 'expired', responded_at = now()
  WHERE status = 'pending' AND expires_at <= now();
  GET DIAGNOSTICS expired_count = ROW_COUNT;
  RETURN expired_count;
END;
$$;

