CREATE TABLE public.captain_line_join_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id integer NOT NULL REFERENCES public.captain_lines(id),
  rider_user_id integer NOT NULL REFERENCES public.users(id),
  trip_date date NOT NULL,
  direction text NOT NULL DEFAULT 'outbound' CHECK (direction IN ('outbound','return')),
  pickup_label text NOT NULL CHECK (length(btrim(pickup_label)) BETWEEN 2 AND 240),
  pickup_lat double precision NOT NULL CHECK (pickup_lat BETWEEN -90 AND 90),
  pickup_lng double precision NOT NULL CHECK (pickup_lng BETWEEN -180 AND 180),
  dropoff_label text NOT NULL CHECK (length(btrim(dropoff_label)) BETWEEN 2 AND 240),
  dropoff_lat double precision NOT NULL CHECK (dropoff_lat BETWEEN -90 AND 90),
  dropoff_lng double precision NOT NULL CHECK (dropoff_lng BETWEEN -180 AND 180),
  seats integer NOT NULL DEFAULT 1 CHECK (seats BETWEEN 1 AND 13),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','cancelled','expired')),
  captain_response text,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT (now() + interval '12 hours'),
  responded_at timestamptz,
  CONSTRAINT captain_line_join_request_response_length CHECK (captain_response IS NULL OR length(captain_response) <= 500)
);

CREATE INDEX captain_line_join_requests_line_date_status_idx
  ON public.captain_line_join_requests(line_id, trip_date, status);
CREATE INDEX captain_line_join_requests_rider_created_idx
  ON public.captain_line_join_requests(rider_user_id, created_at DESC);
CREATE UNIQUE INDEX captain_line_join_requests_one_open_per_rider_line_date_idx
  ON public.captain_line_join_requests(rider_user_id, line_id, trip_date, direction)
  WHERE status IN ('pending','accepted');

CREATE OR REPLACE FUNCTION public.guard_captain_line_with_accepted_riders()
RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, public AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.captain_line_join_requests r
    WHERE r.line_id = OLD.id AND r.status = 'accepted'
      AND r.trip_date >= (now() AT TIME ZONE 'Africa/Cairo')::date
  ) THEN
    RAISE EXCEPTION 'line has accepted rider requests' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_guard_captain_line_with_accepted_riders
BEFORE UPDATE ON public.captain_lines
FOR EACH ROW EXECUTE FUNCTION public.guard_captain_line_with_accepted_riders();

