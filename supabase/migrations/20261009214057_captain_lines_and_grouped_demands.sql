-- Captain-published route offers and rider demand clustering.
-- Existing ride/group records remain intact; this adds the PRD flow alongside them.

CREATE TABLE public.app_config (
  config_key text PRIMARY KEY,
  numeric_value numeric NOT NULL CHECK (numeric_value > 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.app_config(config_key, numeric_value) VALUES
  ('demand_route_radius_km', 2.5),
  ('demand_arrival_window_minutes', 15);

CREATE TABLE public.captain_lines (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  captain_user_id integer NOT NULL REFERENCES public.users(id),
  vehicle_type_id text NOT NULL REFERENCES public.vehicle_types(id),
  origin_label text NOT NULL CHECK (length(btrim(origin_label)) BETWEEN 2 AND 240),
  origin_lat double precision NOT NULL CHECK (origin_lat BETWEEN -90 AND 90),
  origin_lng double precision NOT NULL CHECK (origin_lng BETWEEN -180 AND 180),
  destination_label text NOT NULL CHECK (length(btrim(destination_label)) BETWEEN 2 AND 240),
  destination_lat double precision NOT NULL CHECK (destination_lat BETWEEN -90 AND 90),
  destination_lng double precision NOT NULL CHECK (destination_lng BETWEEN -180 AND 180),
  intermediate_stops jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(intermediate_stops) = 'array'),
  arrival_time time NOT NULL,
  service_days smallint[] NOT NULL CHECK (cardinality(service_days) BETWEEN 1 AND 7 AND service_days <@ ARRAY[0,1,2,3,4,5,6]::smallint[]),
  seats integer NOT NULL CHECK (seats BETWEEN 1 AND 14),
  price_per_seat numeric(10,2) NOT NULL CHECK (price_per_seat >= 0),
  payment_methods text[] NOT NULL DEFAULT ARRAY['cash']::text[] CHECK (cardinality(payment_methods) > 0 AND payment_methods <@ ARRAY['cash','instapay','wallet']::text[]),
  women_only boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','paused','cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX captain_lines_search_idx ON public.captain_lines(vehicle_type_id, status, arrival_time);
CREATE INDEX captain_lines_captain_idx ON public.captain_lines(captain_user_id, created_at DESC);

CREATE TABLE public.demand_groups (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_type_id text NOT NULL REFERENCES public.vehicle_types(id),
  origin_lat double precision NOT NULL CHECK (origin_lat BETWEEN -90 AND 90),
  origin_lng double precision NOT NULL CHECK (origin_lng BETWEEN -180 AND 180),
  destination_lat double precision NOT NULL CHECK (destination_lat BETWEEN -90 AND 90),
  destination_lng double precision NOT NULL CHECK (destination_lng BETWEEN -180 AND 180),
  trip_date date NOT NULL,
  arrival_time time NOT NULL,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','matched','expired','cancelled')),
  captain_line_id integer REFERENCES public.captain_lines(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX demand_groups_match_idx ON public.demand_groups(vehicle_type_id, trip_date, arrival_time) WHERE status = 'open';

CREATE TABLE public.demand_requests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_user_id integer NOT NULL REFERENCES public.users(id),
  demand_group_id integer REFERENCES public.demand_groups(id),
  vehicle_type_id text NOT NULL REFERENCES public.vehicle_types(id),
  trip_date date NOT NULL,
  arrival_time time NOT NULL,
  pickup_label text NOT NULL CHECK (length(btrim(pickup_label)) BETWEEN 2 AND 240),
  pickup_lat double precision NOT NULL CHECK (pickup_lat BETWEEN -90 AND 90),
  pickup_lng double precision NOT NULL CHECK (pickup_lng BETWEEN -180 AND 180),
  dropoff_label text NOT NULL CHECK (length(btrim(dropoff_label)) BETWEEN 2 AND 240),
  dropoff_lat double precision NOT NULL CHECK (dropoff_lat BETWEEN -90 AND 90),
  dropoff_lng double precision NOT NULL CHECK (dropoff_lng BETWEEN -180 AND 180),
  seats integer NOT NULL DEFAULT 1 CHECK (seats BETWEEN 1 AND 14),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','matched','cancelled','expired')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(rider_user_id, demand_group_id)
);
CREATE INDEX demand_requests_rider_idx ON public.demand_requests(rider_user_id, created_at DESC);
CREATE INDEX demand_requests_group_idx ON public.demand_requests(demand_group_id, status);
CREATE TRIGGER trg_demand_requests_rider_role BEFORE INSERT OR UPDATE OF rider_user_id ON public.demand_requests
FOR EACH ROW EXECUTE FUNCTION public.sekka_require_role('rider_user_id','rider');

