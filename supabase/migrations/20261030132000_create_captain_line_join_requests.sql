-- Parent IDs follow the integer keys in the current baseline. Capacity is
-- validated against the selected line, not a separate hard-coded seat limit.
CREATE TABLE public.captain_line_join_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id integer NOT NULL REFERENCES public.captain_lines(id) ON DELETE CASCADE,
  rider_user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  trip_date date NOT NULL,
  direction text NOT NULL CHECK (direction IN ('outbound', 'return')),
  seats smallint NOT NULL CHECK (seats >= 1),
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'accepted', 'rejected', 'cancelled', 'expired')),
  note text NULL CHECK (char_length(note) <= 300),
  expires_at timestamptz NOT NULL,
  decided_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX captain_line_join_requests_offer_status_idx
  ON public.captain_line_join_requests (line_id, trip_date, direction, status);

CREATE INDEX captain_line_join_requests_rider_status_idx
  ON public.captain_line_join_requests (rider_user_id, status);

CREATE INDEX captain_line_join_requests_pending_expiry_idx
  ON public.captain_line_join_requests (expires_at)
  WHERE status = 'pending';

CREATE UNIQUE INDEX captain_line_join_requests_active_unique_idx
  ON public.captain_line_join_requests (line_id, rider_user_id, trip_date, direction)
  WHERE status IN ('pending', 'accepted');

ALTER TABLE public.captain_line_join_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.captain_line_join_requests FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.captain_line_join_requests TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.captain_line_join_requests_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.set_captain_line_join_requests_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_captain_line_join_requests_updated_at ON public.captain_line_join_requests;
CREATE TRIGGER trg_captain_line_join_requests_updated_at
BEFORE UPDATE ON public.captain_line_join_requests
FOR EACH ROW EXECUTE FUNCTION public.set_captain_line_join_requests_updated_at();

REVOKE ALL ON FUNCTION public.set_captain_line_join_requests_updated_at() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.set_captain_line_join_requests_updated_at() TO service_role;