CREATE TABLE public.policy_acceptances (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
  policy_type text NOT NULL CHECK (policy_type IN ('terms', 'privacy')),
  policy_version text NOT NULL CHECK (policy_version ~ '^20[0-9]{2}-[0-9]{2}-[0-9]{2}$'),
  locale text NOT NULL CHECK (locale IN ('ar', 'en')),
  accepted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX policy_acceptances_user_history_idx
  ON public.policy_acceptances(user_id, accepted_at DESC, id DESC);

ALTER TABLE public.policy_acceptances ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.policy_acceptances FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.policy_acceptances TO service_role;

CREATE POLICY policy_acceptances_deny_client_access
  ON public.policy_acceptances AS RESTRICTIVE FOR ALL TO anon, authenticated
  USING (false) WITH CHECK (false);

REVOKE ALL ON SEQUENCE public.policy_acceptances_id_seq FROM PUBLIC, anon, authenticated;

CREATE FUNCTION public.sekka_register_with_policy_acceptance_v1(
  p_full_name text,
  p_phone_number text,
  p_password_hash text,
  p_role text,
  p_policy_locale text
)
RETURNS TABLE(id integer, full_name text, phone_number text, role text, verified_at timestamptz, created_at timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_user public.users%ROWTYPE;
BEGIN
  IF p_role NOT IN ('rider', 'captain') OR p_policy_locale NOT IN ('ar', 'en') THEN
    RAISE EXCEPTION 'invalid signup data' USING ERRCODE = '22023';
  END IF;
  IF length(btrim(p_full_name)) NOT BETWEEN 1 AND 100
     OR length(btrim(p_phone_number)) NOT BETWEEN 1 AND 32
     OR length(p_password_hash) < 1 THEN
    RAISE EXCEPTION 'invalid signup data' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.users (
    full_name, phone_number, password_hash, role,
    terms_accepted_at, terms_version, privacy_version
  ) VALUES (
    btrim(p_full_name), btrim(p_phone_number), p_password_hash, p_role,
    clock_timestamp(), '2026-10-24', '2026-10-24'
  ) RETURNING * INTO v_user;

  INSERT INTO public.policy_acceptances (user_id, policy_type, policy_version, locale)
  VALUES
    (v_user.id, 'terms', '2026-10-24', p_policy_locale),
    (v_user.id, 'privacy', '2026-10-24', p_policy_locale);

  RETURN QUERY SELECT v_user.id, v_user.full_name, v_user.phone_number, v_user.role,
    v_user.verified_at, v_user.created_at;
END;
$$;

REVOKE ALL ON FUNCTION public.sekka_register_with_policy_acceptance_v1(text, text, text, text, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sekka_register_with_policy_acceptance_v1(text, text, text, text, text)
  TO service_role;
